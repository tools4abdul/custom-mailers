import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { adaptKnowledge } from './knowledge-adapter.mjs';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'js/data/knowledge.generated.js');
const defaultLocalPath = resolve(root, '../cliposition/shared/candidates/abdul/data/issues.json');

async function loadCanonicalIssues() {
  const localPath = process.env.CANONICAL_KB_PATH ?? defaultLocalPath;
  try {
    await access(resolve(localPath));
    return JSON.parse(await readFile(resolve(localPath), 'utf8'));
  } catch (error) {
    if (process.env.CANONICAL_KB_URL) {
      const response = await fetch(process.env.CANONICAL_KB_URL);
      if (!response.ok) throw new Error(`Could not load CANONICAL_KB_URL (${response.status} ${response.statusText}).`);
      return response.json();
    }
    if (process.env.CANONICAL_KB_PATH) {
      throw new Error(`Could not read CANONICAL_KB_PATH: ${resolve(localPath)}.`);
    }
    throw new Error(
      `Canonical knowledge base is unavailable. Clone cliposition beside this repository, or set CANONICAL_KB_PATH to shared/candidates/abdul/data/issues.json.`
    );
  }
}

try {
  const issues = adaptKnowledge(await loadCanonicalIssues());
  if (!issues.length) throw new Error('Canonical knowledge base produced no publishable mailer issues.');
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, `// Generated by scripts/sync-knowledge.mjs. Do not edit.\nexport const positions = ${JSON.stringify(issues, null, 2)};\n`);
  console.log(`Prepared ${issues.length} mailer issues from the canonical knowledge base.`);
} catch (error) {
  console.error(`Knowledge-base preparation failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
}
